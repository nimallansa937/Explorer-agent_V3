@dataclass
class GateResult:
    """Result from a single HIFA gate."""
    gate_number: int
    gate_name: str
    passed: bool
    score: float
    threshold: float
    details: Dict[str, Any] = field(default_factory=dict)
    execution_time_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "gate_number": self.gate_number,
            "gate_name": self.gate_name,
            "passed": self.passed,
            "score": self.score,
            "threshold": self.threshold,
            "details": self.details,
            "execution_time_ms": self.execution_time_ms,
        }


@dataclass
class StatisticalScores:
    """Statistical validation scores from HIFA."""
    dsr: float                        # Deflated Sharpe Ratio
    dsr_pvalue: float                 # DSR p-value
    pbo: float                        # Probability of Backtest Overfitting
    pbo_logits: float                 # PBO logit transform
    t_stat: float                     # Strategy t-statistic
    fdr_adjusted_pvalue: float        # FDR-adjusted p-value
    cpcv_sharpe_mean: float           # Mean Sharpe across CPCV paths
    cpcv_sharpe_std: float            # Std Sharpe across CPCV paths
    cpcv_paths_passed: int            # Number of passing CPCV paths
    cpcv_total_paths: int             # Total CPCV paths tested


@dataclass
class BacktestMetrics:
    """Backtest performance metrics."""
    sharpe_ratio: float
    sortino_ratio: float
    max_drawdown: float
    calmar_ratio: float
    win_rate: float
    profit_factor: float
    total_trades: int
    avg_trade_return: float
    avg_trade_duration_hours: float
    start_date: datetime
    end_date: datetime
    total_return: float


@dataclass
class HIFAResult:
    """Complete HIFA v2.0 validation result."""
    strategy_id: str
    passed: bool
    final_gate: int                   # Last gate passed (1-7)
    gate_results: Dict[int, GateResult]
    statistical_scores: Optional[StatisticalScores]
    backtest_metrics: Optional[BacktestMetrics]
    regime_tier: RegimeTier
    regime_performance: Dict[str, float]  # Sharpe per regime
    cluster_id: Optional[int]         # HRP cluster assignment
    similarity_score: Optional[float]  # Max similarity to existing strategies
    rejection_reason: Optional[str]
    validation_timestamp: datetime = field(default_factory=datetime.now)
    total_execution_time_ms: float = 0.0

    @property
    def backtest_sharpe(self) -> float:
        """Convenience accessor for backtest Sharpe."""
        if self.backtest_metrics:
            return self.backtest_metrics.sharpe_ratio
        return 0.0

    @property
    def backtest_max_dd(self) -> float:
        """Convenience accessor for backtest max drawdown."""
        if self.backtest_metrics:
            return self.backtest_metrics.max_drawdown
        return 1.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "strategy_id": self.strategy_id,
            "passed": self.passed,
            "final_gate": self.final_gate,
            "gate_results": {k: v.to_dict() for k, v in self.gate_results.items()},
            "backtest_sharpe": self.backtest_sharpe,
            "backtest_max_dd": self.backtest_max_dd,
            "regime_tier": self.regime_tier.value,
            "rejection_reason": self.rejection_reason,
            "validation_timestamp": self.validation_timestamp.isoformat(),
        }


