"""
Unified Strategy Format for EXPLORER PRIME

This module defines the canonical strategy representation that flows through
the entire pipeline:
- Generation (Explorer v3.0, LSM)
- Validation (HIFA v2.0)
- Forward Testing (Hinance)
- Production Storage (EMT)

Key Classes:
- StrategyGenome: Core strategy logic representation
- UnifiedStrategy: Complete strategy package with metadata
- HIFAResult: Historical validation results
- ForwardTestResult: Live testing results
- ProductionStrategy: Final production-ready strategy
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, Tuple
from datetime import datetime
from enum import Enum
import json
import hashlib
import uuid


class StrategyStatus(Enum):
    """Strategy lifecycle status."""
    GENERATED = "generated"           # Just created
    HIFA_VALIDATING = "hifa_validating"  # In HIFA pipeline
    HIFA_PASSED = "hifa_passed"       # Passed HIFA
    HIFA_FAILED = "hifa_failed"       # Failed HIFA
    SHADOW_TRADING = "shadow_trading"  # In forward testing
    FORWARD_PASSED = "forward_passed"  # Passed forward testing
    FORWARD_FAILED = "forward_failed"  # Failed forward testing
    PRODUCTION = "production"         # Active in production
    MONITORING = "monitoring"         # Under performance watch
    RETIRED = "retired"               # Retired from production


class SourceEngine(Enum):
    """Strategy generation source."""
    EVOLUTIONARY = "evolutionary"
    GENAI = "genai"
    PATTERN = "pattern"
    RECOMBINE = "recombine"
    LSM = "lsm"
    MANUAL = "manual"
    EXTERNAL = "external"


class RegimeTier(Enum):
    """Strategy regime classification."""
    ALL_WEATHER = "all_weather"       # Works in all regimes
    REGIME_SPECIFIC = "regime_specific"  # Only works in specific regimes
    UNKNOWN = "unknown"


