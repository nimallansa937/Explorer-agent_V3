@dataclass
class ConditionNode:
    """Single condition in strategy logic tree."""
    operator: str                     # "and", "or", "gt", "lt", "eq", etc.
    left: Any                         # Left operand (indicator, value, or nested node)
    right: Any                        # Right operand
    children: List['ConditionNode'] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary."""
        return {
            "operator": self.operator,
            "left": self.left if not isinstance(self.left, ConditionNode) else self.left.to_dict(),
            "right": self.right if not isinstance(self.right, ConditionNode) else self.right.to_dict(),
            "children": [c.to_dict() for c in self.children],
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'ConditionNode':
        """Deserialize from dictionary."""
        return cls(
            operator=data["operator"],
            left=cls.from_dict(data["left"]) if isinstance(data["left"], dict) and "operator" in data["left"] else data["left"],
            right=cls.from_dict(data["right"]) if isinstance(data["right"], dict) and "operator" in data["right"] else data["right"],
            children=[cls.from_dict(c) for c in data.get("children", [])],
        )


@dataclass
class StrategyGenome:
    """
    Universal strategy representation.

    This is the canonical format that can be:
    - Generated by any engine (Explorer, LSM, Pattern, etc.)
    - Validated by HIFA v2.0
    - Executed by Hinance forward testing
    - Stored in EMT for production

    Supports conversion to/from:
    - Explorer v3.0 StrategyPosterior
    - LSM token sequences
    - Hinance genome_json
    - Executable Python code
    """

    # Core logic (tree structure)
    entry_conditions: List[Dict[str, Any]]    # When to enter
    exit_conditions: List[Dict[str, Any]]     # When to exit
    position_sizing: Dict[str, Any]           # How much to trade

    # Parameters
    parameters: Dict[str, float]              # Tunable parameters
    lookback_periods: Dict[str, int]          # Data windows

    # Indicators used
    indicators: List[str]                     # ["RSI", "MACD", "BB", ...]

    # Risk management
    stop_loss_pct: Optional[float] = None     # Stop loss percentage
    take_profit_pct: Optional[float] = None   # Take profit percentage
    max_position_size: float = 1.0            # Maximum position (0-1)

    # Complexity metrics (computed)
    n_parameters: int = field(init=False)
    n_rules: int = field(init=False)
    tree_depth: int = field(init=False)

    def __post_init__(self):
        """Compute derived metrics."""
        self.n_parameters = len(self.parameters)
        self.n_rules = len(self.entry_conditions) + len(self.exit_conditions)
        self.tree_depth = self._calculate_depth()

    def _calculate_depth(self) -> int:
        """Calculate max depth of condition tree."""
        def depth(node: Any) -> int:
            if isinstance(node, dict):
                if 'children' in node and node['children']:
                    return 1 + max(depth(c) for c in node['children'])
                elif 'left' in node or 'right' in node:
                    left_depth = depth(node.get('left', {}))
                    right_depth = depth(node.get('right', {}))
                    return 1 + max(left_depth, right_depth)
            return 1

        max_depth = 0
        for cond in self.entry_conditions + self.exit_conditions:
            max_depth = max(max_depth, depth(cond))
        return max_depth

    def compute_hash(self) -> str:
        """Compute unique hash for the genome."""
        content = json.dumps({
            "entry": self.entry_conditions,
            "exit": self.exit_conditions,
            "sizing": self.position_sizing,
            "params": self.parameters,
            "indicators": sorted(self.indicators),
        }, sort_keys=True)
        return hashlib.sha256(content.encode()).hexdigest()[:16]

    def to_json(self) -> str:
        """Serialize to JSON for storage/transmission."""
        return json.dumps({
            "entry_conditions": self.entry_conditions,
            "exit_conditions": self.exit_conditions,
            "position_sizing": self.position_sizing,
            "parameters": self.parameters,
            "lookback_periods": self.lookback_periods,
            "indicators": self.indicators,
            "stop_loss_pct": self.stop_loss_pct,
            "take_profit_pct": self.take_profit_pct,
            "max_position_size": self.max_position_size,
        }, indent=2)

    @classmethod
    def from_json(cls, json_str: str) -> 'StrategyGenome':
        """Deserialize from JSON."""
        data = json.loads(json_str)
        return cls(
            entry_conditions=data["entry_conditions"],
            exit_conditions=data["exit_conditions"],
            position_sizing=data["position_sizing"],
            parameters=data["parameters"],
            lookback_periods=data["lookback_periods"],
            indicators=data["indicators"],
            stop_loss_pct=data.get("stop_loss_pct"),
            take_profit_pct=data.get("take_profit_pct"),
            max_position_size=data.get("max_position_size", 1.0),
        )

    def to_executable(self, language: str = "python") -> str:
        """Generate executable trading code."""
        if language == "python":
            return self._to_python()
        raise ValueError(f"Unsupported language: {language}")

    def _to_python(self) -> str:
        """Generate Python trading code."""
        lines = [
            "# Auto-generated strategy code",
            "# DO NOT EDIT MANUALLY",
            "",
            "from typing import Dict, Any",
            "import numpy as np",
            "",
            "class GeneratedStrategy:",
            "    '''Strategy generated from genome.'''",
            "",
            f"    INDICATORS = {self.indicators}",
            f"    PARAMETERS = {self.parameters}",
            f"    LOOKBACKS = {self.lookback_periods}",
            "",
            "    def __init__(self):",
            f"        self.stop_loss = {self.stop_loss_pct}",
            f"        self.take_profit = {self.take_profit_pct}",
            f"        self.max_position = {self.max_position_size}",
            "",
            "    def should_enter(self, features: Dict[str, Any]) -> bool:",
            "        '''Check entry conditions.'''",
            f"        # Entry rules: {len(self.entry_conditions)}",
            "        return self._evaluate_conditions(features, 'entry')",
            "",
            "    def should_exit(self, features: Dict[str, Any]) -> bool:",
            "        '''Check exit conditions.'''",
            f"        # Exit rules: {len(self.exit_conditions)}",
            "        return self._evaluate_conditions(features, 'exit')",
            "",
            "    def get_position_size(self, features: Dict[str, Any]) -> float:",
            "        '''Calculate position size.'''",
            f"        # Sizing method: {self.position_sizing.get('method', 'fixed')}",
            "        return min(self._calculate_size(features), self.max_position)",
        ]
        return "\n".join(lines)

    def validate(self) -> Tuple[bool, List[str]]:
        """Validate genome structure."""
        errors = []

        # Check required fields
        if not self.entry_conditions:
            errors.append("No entry conditions defined")
        if not self.exit_conditions:
            errors.append("No exit conditions defined")
        if not self.indicators:
            errors.append("No indicators specified")

        # Check complexity limits
        from .constants import (
            MAX_STRATEGY_PARAMETERS,
            MAX_STRATEGY_RULES,
            MAX_STRATEGY_TREE_DEPTH,
            MAX_STRATEGY_INDICATORS,
        )

        if self.n_parameters > MAX_STRATEGY_PARAMETERS:
            errors.append(f"Too many parameters: {self.n_parameters} > {MAX_STRATEGY_PARAMETERS}")
        if self.n_rules > MAX_STRATEGY_RULES:
            errors.append(f"Too many rules: {self.n_rules} > {MAX_STRATEGY_RULES}")
        if self.tree_depth > MAX_STRATEGY_TREE_DEPTH:
            errors.append(f"Tree too deep: {self.tree_depth} > {MAX_STRATEGY_TREE_DEPTH}")
        if len(self.indicators) > MAX_STRATEGY_INDICATORS:
            errors.append(f"Too many indicators: {len(self.indicators)} > {MAX_STRATEGY_INDICATORS}")

        return len(errors) == 0, errors


