@dataclass
class UnifiedStrategy:
    """
    Complete strategy package that flows through entire pipeline.

    This is the central data structure that carries a strategy from
    generation through validation to production.
    """

    # Identity
    strategy_id: str = field(default_factory=lambda: f"strat_{uuid.uuid4().hex[:12]}")
    version: str = "1.0"

    # Core content
    genome: Optional[StrategyGenome] = None

    # Provenance
    source_engine: SourceEngine = SourceEngine.MANUAL
    generation_timestamp: datetime = field(default_factory=datetime.now)
    parent_strategies: List[str] = field(default_factory=list)  # For recombination

    # Conditioning (what market state it was designed for)
    target_regime: Optional[str] = None       # "normal", "elevated", "crisis"
    target_volatility: Optional[str] = None   # "low", "medium", "high"
    target_asset: str = "BTCUSDT"

    # Validation state (updated as it passes gates)
    status: StrategyStatus = StrategyStatus.GENERATED
    hifa_result: Optional[HIFAResult] = None
    forward_result: Optional[ForwardTestResult] = None

    # Production state
    production_start: Optional[datetime] = None
    production_end: Optional[datetime] = None
    retirement_reason: Optional[str] = None

    # Metadata
    metadata: Dict[str, Any] = field(default_factory=dict)
    tags: List[str] = field(default_factory=list)

    @property
    def is_hifa_validated(self) -> bool:
        """Check if strategy passed HIFA validation."""
        return self.hifa_result is not None and self.hifa_result.passed

    @property
    def is_forward_validated(self) -> bool:
        """Check if strategy passed forward testing."""
        return self.forward_result is not None and self.forward_result.passed

    @property
    def is_production_ready(self) -> bool:
        """Check if strategy is ready for production."""
        return self.is_hifa_validated and self.is_forward_validated

    @property
    def genome_hash(self) -> Optional[str]:
        """Get genome hash for deduplication."""
        if self.genome:
            return self.genome.compute_hash()
        return None

    def update_status(self, new_status: StrategyStatus):
        """Update strategy status with validation."""
        valid_transitions = {
            StrategyStatus.GENERATED: [StrategyStatus.HIFA_VALIDATING],
            StrategyStatus.HIFA_VALIDATING: [StrategyStatus.HIFA_PASSED, StrategyStatus.HIFA_FAILED],
            StrategyStatus.HIFA_PASSED: [StrategyStatus.SHADOW_TRADING],
            StrategyStatus.HIFA_FAILED: [],  # Terminal
            StrategyStatus.SHADOW_TRADING: [StrategyStatus.FORWARD_PASSED, StrategyStatus.FORWARD_FAILED],
            StrategyStatus.FORWARD_PASSED: [StrategyStatus.PRODUCTION],
            StrategyStatus.FORWARD_FAILED: [],  # Terminal
            StrategyStatus.PRODUCTION: [StrategyStatus.MONITORING, StrategyStatus.RETIRED],
            StrategyStatus.MONITORING: [StrategyStatus.PRODUCTION, StrategyStatus.RETIRED],
            StrategyStatus.RETIRED: [],  # Terminal
        }

        if new_status not in valid_transitions.get(self.status, []):
            raise ValueError(f"Invalid status transition: {self.status} -> {new_status}")

        self.status = new_status

    def attach_hifa_result(self, result: HIFAResult):
        """Attach HIFA validation result."""
        self.hifa_result = result
        if result.passed:
            self.status = StrategyStatus.HIFA_PASSED
        else:
            self.status = StrategyStatus.HIFA_FAILED

    def attach_forward_result(self, result: ForwardTestResult):
        """Attach forward testing result."""
        self.forward_result = result
        if result.passed:
            self.status = StrategyStatus.FORWARD_PASSED
        else:
            self.status = StrategyStatus.FORWARD_FAILED

    def promote_to_production(self):
        """Promote strategy to production status."""
        if not self.is_production_ready:
            raise ValueError("Strategy must pass both HIFA and forward testing")
        self.status = StrategyStatus.PRODUCTION
        self.production_start = datetime.now()

    def retire(self, reason: str):
        """Retire strategy from production."""
        self.status = StrategyStatus.RETIRED
        self.production_end = datetime.now()
        self.retirement_reason = reason

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dictionary."""
        return {
            "strategy_id": self.strategy_id,
            "version": self.version,
            "genome_hash": self.genome_hash,
            "source_engine": self.source_engine.value,
            "generation_timestamp": self.generation_timestamp.isoformat(),
            "target_asset": self.target_asset,
            "target_regime": self.target_regime,
            "status": self.status.value,
            "is_hifa_validated": self.is_hifa_validated,
            "is_forward_validated": self.is_forward_validated,
            "is_production_ready": self.is_production_ready,
            "tags": self.tags,
        }

    def to_json(self) -> str:
        """Serialize to JSON."""
        data = self.to_dict()
        if self.genome:
            data["genome"] = json.loads(self.genome.to_json())
        if self.hifa_result:
            data["hifa_result"] = self.hifa_result.to_dict()
        if self.forward_result:
            data["forward_result"] = self.forward_result.to_dict()
        return json.dumps(data, indent=2, default=str)

    @classmethod
    def from_json(cls, json_str: str) -> 'UnifiedStrategy':
        """Deserialize from JSON."""
        data = json.loads(json_str)

        genome = None
        if "genome" in data:
            genome = StrategyGenome.from_json(json.dumps(data["genome"]))

        return cls(
            strategy_id=data["strategy_id"],
            version=data.get("version", "1.0"),
            genome=genome,
            source_engine=SourceEngine(data.get("source_engine", "manual")),
            target_asset=data.get("target_asset", "BTCUSDT"),
            target_regime=data.get("target_regime"),
            status=StrategyStatus(data.get("status", "generated")),
            tags=data.get("tags", []),
        )


