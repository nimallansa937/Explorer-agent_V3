@dataclass
class ProductionStrategy:
    """
    Production-ready strategy with all validation complete.

    This is the final format stored in EMT for active trading.
    """
    strategy_id: str
    genome: StrategyGenome
    backtest_metrics: BacktestMetrics
    shadow_metrics: ShadowMetrics
    transfer_ratio: float
    regime_tier: RegimeTier
    cluster_id: int

    # Production tracking
    production_start: datetime
    status: str = "active"            # "active", "monitoring", "retired"

    # Performance tracking
    live_trades: int = 0
    live_sharpe: Optional[float] = None
    live_max_dd: Optional[float] = None
    last_trade_time: Optional[datetime] = None

    # Metadata
    source_engine: str = "unknown"
    tags: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "strategy_id": self.strategy_id,
            "transfer_ratio": self.transfer_ratio,
            "regime_tier": self.regime_tier.value,
            "cluster_id": self.cluster_id,
            "production_start": self.production_start.isoformat(),
            "status": self.status,
            "live_trades": self.live_trades,
            "live_sharpe": self.live_sharpe,
            "source_engine": self.source_engine,
        }
