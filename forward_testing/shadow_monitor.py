@dataclass
class MonitorConfig:
    """Configuration for shadow monitor."""

    # Drawdown thresholds
    drawdown_warning_pct: float = 10.0  # Warn at 10% DD
    drawdown_critical_pct: float = 15.0  # Critical at 15% DD
    drawdown_emergency_pct: float = 20.0  # Emergency at 20% DD

    # Performance thresholds
    losing_streak_warning: int = 5  # Warn after 5 consecutive losses
    losing_streak_critical: int = 8  # Critical after 8
    max_daily_loss_pct: float = 5.0  # Max 5% daily loss

    # Transfer ratio monitoring
    transfer_ratio_warning: float = 0.6  # Warn if ratio drops below 0.6
    transfer_ratio_critical: float = 0.4  # Critical below 0.4

    # Execution quality
    slippage_warning_bps: float = 15.0  # Warn at 15 bps avg
    slippage_critical_bps: float = 30.0  # Critical at 30 bps
    max_rejection_rate: float = 0.10  # Max 10% order rejections

    # Data freshness
    stale_data_seconds: int = 300  # Alert if no update for 5 min
    health_check_interval_seconds: int = 60

    # Auto-actions
    auto_pause_on_drawdown_emergency: bool = True
    auto_pause_on_losing_streak: bool = False
    notify_on_regime_change: bool = True

    # Milestones
    duration_milestones_days: List[int] = field(default_factory=lambda: [1, 7, 14, 21])
    trade_milestones: List[int] = field(default_factory=lambda: [10, 30, 50, 100])


# ==============================================================================
# Strategy Health Tracker
# ==============================================================================

@dataclass
class StrategyHealth:
    """Health status for a single strategy."""
    strategy_id: str = ""

    # Current metrics
    current_pnl: float = 0.0
    current_drawdown_pct: float = 0.0
    current_sharpe: float = 0.0
    transfer_ratio: float = 0.0

    # Trade tracking
    total_trades: int = 0
    winning_trades: int = 0
    consecutive_losses: int = 0
    consecutive_wins: int = 0

    # Daily tracking
    daily_pnl: float = 0.0
    daily_trades: int = 0
    daily_start_equity: float = 0.0

    # Execution quality
    avg_slippage_bps: float = 0.0
    rejection_count: int = 0
    total_orders: int = 0

    # Timing
    last_trade_time: Optional[datetime] = None
    last_update_time: datetime = field(default_factory=datetime.now)
    session_start: datetime = field(default_factory=datetime.now)

    # Status
    is_healthy: bool = True
    is_paused: bool = False
    warnings: List[str] = field(default_factory=list)

    # Recent trades (rolling window)
    recent_pnl: deque = field(default_factory=lambda: deque(maxlen=20))

    @property
    def duration_days(self) -> float:
        return (datetime.now() - self.session_start).total_seconds() / 86400

    @property
    def win_rate(self) -> float:
        return self.winning_trades / self.total_trades if self.total_trades > 0 else 0

    @property
    def rejection_rate(self) -> float:
        return self.rejection_count / self.total_orders if self.total_orders > 0 else 0


