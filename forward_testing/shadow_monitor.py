class AlertLevel(Enum):
    """Alert severity levels."""
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"
    EMERGENCY = "EMERGENCY"


class AlertType(Enum):
    """Types of monitoring alerts."""
    # Performance alerts
    DRAWDOWN_WARNING = "DRAWDOWN_WARNING"
    DRAWDOWN_CRITICAL = "DRAWDOWN_CRITICAL"
    LOSING_STREAK = "LOSING_STREAK"
    PERFORMANCE_DEGRADATION = "PERFORMANCE_DEGRADATION"
    TRANSFER_RATIO_LOW = "TRANSFER_RATIO_LOW"

    # Execution alerts
    HIGH_SLIPPAGE = "HIGH_SLIPPAGE"
    EXECUTION_FAILURE = "EXECUTION_FAILURE"
    ORDER_REJECTION = "ORDER_REJECTION"

    # System alerts
    REGIME_CHANGE = "REGIME_CHANGE"
    VOLATILITY_SPIKE = "VOLATILITY_SPIKE"
    LIQUIDITY_WARNING = "LIQUIDITY_WARNING"

    # Lifecycle alerts
    SESSION_STARTED = "SESSION_STARTED"
    SESSION_COMPLETED = "SESSION_COMPLETED"
    SESSION_FAILED = "SESSION_FAILED"
    DURATION_MILESTONE = "DURATION_MILESTONE"

    # Health alerts
    STALE_DATA = "STALE_DATA"
    CONNECTION_ISSUE = "CONNECTION_ISSUE"
    HEALTH_CHECK_FAILED = "HEALTH_CHECK_FAILED"


@dataclass
class MonitorAlert:
    """Alert generated by the monitor."""
    id: str = ""
    strategy_id: str = ""
    alert_type: AlertType = AlertType.PERFORMANCE_DEGRADATION
    level: AlertLevel = AlertLevel.INFO

    # Alert details
    message: str = ""
    details: Dict[str, Any] = field(default_factory=dict)

    # Context
    current_value: float = 0.0
    threshold_value: float = 0.0

    # Timing
    timestamp: datetime = field(default_factory=datetime.now)
    acknowledged: bool = False
    acknowledged_at: Optional[datetime] = None

    # Actions taken
    auto_action: Optional[str] = None
    action_result: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            'id': self.id,
            'strategy_id': self.strategy_id,
            'alert_type': self.alert_type.value,
            'level': self.level.value,
            'message': self.message,
            'details': self.details,
            'current_value': self.current_value,
            'threshold_value': self.threshold_value,
            'timestamp': self.timestamp.isoformat(),
            'acknowledged': self.acknowledged,
            'auto_action': self.auto_action,
        }


